"""Run: .venv/bin/python scripts/power_expC.py (OPENROUTER_API_KEY may be any value; no API calls).
Design (power) analysis for Experiment C before C2: synthetic data only, no run data.
World 'rule': groups generated by the frozen rule (R3, rounds-left bins), round 1 drawn agent by agent
from the cell's stage-1 round 1. World 'R0': collapse decided by the deterministic isolated-response
rule from the same kind of round 1 (no extra noise). C-H1 labels with the analysis code's own
bootstrap and label functions; C-H3 (Mistral n16) with conditional predictions from the rule."""
import sys, numpy as np
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import pgg_analysis_expB as pb, pgg_analysis_expC as pc
fz = pb.load_frozen(ROOT / "data/expB/frozen_rules_v1.json", pc.FROZEN_SHA)
G = {"mistral": 6, "gpt": 12}
BIG = {"mistral": 16, "gpt": 32}
rng = np.random.default_rng(20261019)

def draw(model, card, n, g, world):
    cell = fz["models"][model]["cells"][card]
    pool = np.array(cell["round1"], float).ravel()
    c1 = rng.choice(pool, size=(g, n))
    if world == "rule":
        traj = pc.simulate_rule(pb.rules_for(fz, model, card, "R3"), c1, rng)
    else:
        traj = pc.simulate_r0(cell["iso_f"], c1)
    return traj

def ch1(model, world, n_boot=2000):
    obs = {n: [pc.outcomes(draw(model, c, n, G[model], world))[0] for c in pc.CARDS] for n in (4, BIG[model])}
    b = np.random.default_rng(rng.integers(1 << 30))
    est = pc.pooled_mean(obs[BIG[model]]) - pc.pooled_mean(obs[4])
    ci = pc.pa.ci(pc.strat_boot(obs[BIG[model]], b, n_boot) - pc.strat_boot(obs[4], b, n_boot))
    return pc.label_size({"est": est, "ci": ci}), est

for model in ("mistral", "gpt"):
    for world in ("rule", "R0"):
        labs, ests = [], []
        for _ in range(300):
            l, e = ch1(model, world); labs.append(l); ests.append(e)
        from collections import Counter
        c = Counter(labs)
        print(f"C-H1 {model:8s} world={world:4s} n=4 vs {BIG[model]}: " + ", ".join(f"{k} {v/len(labs):.2f}" for k, v in c.most_common()) + f" | mean est {np.mean(ests):+.3f}")

# C-H3 (Mistral, n16) and C-H2 under the rule world: conditional predictions from observed round 1
from collections import Counter
lab3, lab2 = Counter(), Counter()
for rep in range(40):
    arrays = {("mistral", c): draw("mistral", c, 16, 6, "rule") for c in pc.CARDS}
    arrays4 = {("mistral", c): draw("mistral", c, 4, 6, "rule") for c in pc.CARDS}
    class U(pc.UnitsN):
        def __init__(self, arr, n):
            super().__init__([], n=n)
            for (m, c), A in arr.items():
                for k, g in enumerate(A):
                    self.groups[f"{m}|{c}|{k}"] = {"model": m, "card": c, "c": g, "capped": False, "length": False, "comp_full": True}
    res = pc.analyse(fz, {4: U(arrays4, 4), 16: U(arrays, 16)}, s=100, n_boot=1000, sizes={"mistral": (4, 16)})
    lab3[res["C_H3"]["mistral"]["16"]["label"]] += 1
    lab2[res["C_H2"]["mistral"]["family"]["16"]["label"]] += 1
print("C-H3 mistral n16, rule world:", dict(lab3))
print("C-H2 mistral n16, rule world:", dict(lab2))
